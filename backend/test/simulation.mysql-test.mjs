import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import test from 'node:test';
import { ValidationPipe } from '@nestjs/common';
import { NestFactory } from '@nestjs/core';
import { JwtService } from '@nestjs/jwt';
import request from 'supertest';
import { AppModule } from '../dist/src/app.module.js';
import { PrismaService } from '../dist/src/prisma/prisma.service.js';

test('demo registration, secure pairing, policy acknowledgement and revocation work together in MySQL', async () => {
  assert.equal(process.env.NODE_ENV, 'test', 'Use NODE_ENV=test.');
  assert.match(process.env.MYSQL_DATABASE ?? '', /_test$/, 'Use a dedicated database ending in _test.');
  const app = await NestFactory.create(AppModule, { logger: false });
  app.useGlobalPipes(new ValidationPipe({ whitelist: true, forbidNonWhitelisted: true, transform: true }));
  await app.init();
  const prisma = app.get(PrismaService);
  const http = request(app.getHttpServer());
  const guardians = [];
  const devices = [];
  try {
    for (let i = 0; i < 2; i += 1) guardians.push(await prisma.guardian.create({ data: { email: `${randomUUID()}@example.test`, name: 'Simulation test', passwordHash: 'unused-test-hash' } }));
    const tokens = await Promise.all(guardians.map((guardian) => app.get(JwtService).signAsync({ sub: guardian.id })));
    const auth = (token) => `Bearer ${token}`;
    await http.post('/simulation/devices').send({ name: 'PC' }).expect(401);
    await http.post('/simulation/devices').set('Authorization', auth(tokens[0])).send({ name: 'PC', isDemo: false }).expect(400);
    const registration = await http.post('/simulation/devices').set('Authorization', auth(tokens[0])).send({ name: 'PC teste', managedUser: 'Ana' }).expect(201);
    assert.equal(registration.headers['cache-control'], 'no-store');
    const { device, credential } = registration.body;
    devices.push(device.id);
    assert.equal(device.isDemo, true);
    assert.match(credential, /^[A-Za-z0-9_-]{43}$/);
    const guardianGet = (token = tokens[0]) => http.get(`/simulation/devices/${device.id}`).set('Authorization', auth(token));
    const agentGet = () => http.get('/agent/simulation').set('Authorization', auth(credential));
    const agentReport = (body) => http.put('/agent/simulation').set('Authorization', auth(credential)).send(body);
    const heartbeat = (associationId) => http.post('/agent/simulation/heartbeat').set('Authorization', auth(credential)).send({ associationId });
    const patch = (revision, settings) => http.patch(`/simulation/devices/${device.id}`).set('Authorization', auth(tokens[0])).send({ revision, settings });
    async function pair(guardianToken) {
      const session = await http.post('/agent/pairing-sessions').set('Authorization', auth(credential)).send({}).expect(201);
      await http.post('/pairing/validate').set('Authorization', auth(guardianToken)).send({ token: session.body.token }).expect(200);
      return http.post('/pairing/complete').set('Authorization', auth(guardianToken)).send({ token: session.body.token }).expect(200);
    }
    await guardianGet().expect(404);
    await agentGet().expect(404);
    await pair(tokens[0]);
    await guardianGet(tokens[1]).expect(404);
    const first = (await guardianGet().expect(200)).body;
    assert.equal(first.appliedRevision, null);
    assert.equal(first.revision, 1);
    assert.deepEqual(first.connection, { status: 'unverified', lastSeen: null });
    await http.post('/agent/simulation/heartbeat').send({ associationId: first.associationId }).expect(401);
    await heartbeat(device.id).expect(409);
    const contact = (await heartbeat(first.associationId).expect(201)).body;
    assert.equal(contact.connection.status, 'online');
    assert.equal(contact.appliedRevision, null);
    assert.equal(contact.revision, 1);
    let listed = await http.get('/devices').set('Authorization', auth(tokens[0])).expect(200);
    assert.equal(listed.body.find((item) => item.id === device.id).status, 'online');
    const expiredAt = new Date(Date.now() - 16000);
    await prisma.simulationState.update({ where: { associationId: first.associationId }, data: { lastSeenAt: expiredAt } });
    const offline = (await guardianGet().expect(200)).body;
    assert.equal(offline.connection.status, 'offline');
    assert.equal(offline.connection.lastSeen, expiredAt.toISOString());
    listed = await http.get('/devices').set('Authorization', auth(tokens[0])).expect(200);
    assert.equal(listed.body.find((item) => item.id === device.id).status, 'offline');
    assert.equal(JSON.stringify(first).includes(credential), false);
    const application = { id: randomUUID(), name: 'Firefox', category: 'Navegador' };
    const installation = { id: randomUUID(), applicationName: 'GIMP', requesterName: 'Ana', requestedAt: new Date().toISOString(), ageRating: '12' };
    const report = { associationId: first.associationId, revision: 1, applications: [application], installationRequests: [installation] };
    await http.get(`/devices/${device.id}/applications`).set('Authorization', auth(tokens[0])).expect(503);
    await agentReport(report).expect(200);
    const saved = (await patch(1, { ageRating: '16', blockBrowsers: false, allowedBrowsers: { brave: true }, blockInstallation: false, applicationRules: { [application.id]: false }, installationDecisions: { [installation.id]: 'DENIED' } }).expect(200)).body;
    assert.equal(saved.revision, 2);
    assert.equal(saved.appliedRevision, 1);
    await agentReport(report).expect(409);
    const confirmed = (await agentReport({ ...report, revision: 2 }).expect(200)).body;
    assert.equal(confirmed.appliedRevision, 2);
    assert.equal(confirmed.settings.ageRating, '16');
    const apps = await http.get(`/devices/${device.id}/applications`).set('Authorization', auth(tokens[0])).expect(200);
    assert.equal(apps.body[0].allowed, false);
    await http.get(`/devices/${device.id}/installation-requests`).set('Authorization', auth(tokens[0])).expect(200).expect([]);
    await agentReport({ ...report, revision: 2 }).expect(200);
    assert.equal(await prisma.installedApplication.count({ where: { deviceId: device.id } }), 1);
    const concurrent = await Promise.all([patch(2, { ageRating: '10' }), patch(2, { ageRating: '18' })]);
    assert.deepEqual(concurrent.map((response) => response.status).sort(), [200, 409]);
    await http.delete(`/devices/${device.id}/association`).set('Authorization', auth(tokens[0])).expect(204);
    await guardianGet().expect(404);
    await agentGet().expect(404);
    await heartbeat(first.associationId).expect(404);
    await agentReport({ ...report, revision: 2 }).expect(404);
    await pair(tokens[1]);
    const next = (await guardianGet(tokens[1]).expect(200)).body;
    assert.notEqual(next.associationId, first.associationId);
    assert.equal(next.settings.ageRating, '12');
    assert.equal(next.appliedRevision, null);
    assert.deepEqual(next.connection, { status: 'unverified', lastSeen: null });
    await heartbeat(first.associationId).expect(409);
    await agentReport({ ...report, revision: 2 }).expect(409);
    process.env.NODE_ENV = 'production';
    await http.post('/simulation/devices').set('Authorization', auth(tokens[0])).send({ name: 'PC' }).expect(404);
    await guardianGet(tokens[1]).expect(404);
    await agentGet().expect(401);
    await http.delete('/agent/simulation').set('Authorization', auth(credential)).expect(401);
    process.env.NODE_ENV = 'test';
    const other = await http.post('/simulation/devices').set('Authorization', auth(tokens[0])).send({ name: 'Outro PC' }).expect(201);
    devices.push(other.body.device.id);
    await prisma.device.update({ where: { id: other.body.device.id }, data: { isDemo: false } });
    await http.delete('/agent/simulation').set('Authorization', auth(other.body.credential)).expect(404);
    await prisma.device.update({ where: { id: other.body.device.id }, data: { isDemo: true } });
    await http.delete('/agent/simulation').expect(401);
    await http.delete('/agent/simulation').set('Authorization', auth(tokens[0])).expect(401);
    await prisma.agentCommand.create({ data: { deviceId: device.id, associationId: next.associationId, requestId: randomUUID(), type: 'agent.ping', version: 1, parameters: {}, expiresAt: new Date(Date.now() + 60000) } });
    const reset = await http.delete('/agent/simulation').set('Authorization', auth(credential)).expect(200);
    assert.deepEqual(reset.body, { deletedDeviceId: device.id });
    assert.equal(await prisma.device.count({ where: { id: device.id } }), 0);
    for (const model of ['agentCommand', 'deviceAssociation', 'agentIdentity', 'pairingSession', 'installedApplication', 'installationRequest']) {
      assert.equal(await prisma[model].count({ where: { deviceId: device.id } }), 0);
    }
    assert.equal(await prisma.simulationState.count({ where: { associationId: { in: [first.associationId, next.associationId] } } }), 0);
    assert.equal(await prisma.device.count({ where: { id: other.body.device.id } }), 1);
    assert.equal(await prisma.guardian.count({ where: { id: { in: guardians.map((g) => g.id) } } }), 2);
    await agentGet().expect(401);
    const unpairedReset = await http.delete('/agent/simulation').set('Authorization', auth(other.body.credential)).expect(200);
    assert.equal(unpairedReset.body.deletedDeviceId, other.body.device.id);
  } finally {
    process.env.NODE_ENV = 'test';
    await prisma.deviceAssociation.deleteMany({ where: { deviceId: { in: devices } } });
    await prisma.pairingSession.deleteMany({ where: { deviceId: { in: devices } } });
    await prisma.device.deleteMany({ where: { id: { in: devices } } });
    await prisma.guardian.deleteMany({ where: { id: { in: guardians.map((guardian) => guardian.id) } } });
    await app.close();
  }
});
